// Creates src/environments/environment.local.ts (git-ignored) before serve/build/test.
// - If GOOGLE_MAPS_API_KEY is set, the file is (re)written with that key and any TURN_* settings.
// - Otherwise an existing file is kept, or a placeholder file without a key is created.
//
// TURN relay for party mode (needed when phones and host are on different networks):
//   TURN_URLS        comma-separated, e.g. "turn:global.relay.metered.ca:80,turns:global.relay.metered.ca:443?transport=tcp"
//   TURN_USERNAME    relay username
//   TURN_CREDENTIAL  relay password
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'environments', 'environment.local.ts');
const key = process.env.GOOGLE_MAPS_API_KEY?.trim();
const turnUrls = (process.env.TURN_URLS ?? '')
  .split(',')
  .map((u) => u.trim())
  .filter(Boolean);
const turnServers = turnUrls.length
  ? [
      {
        urls: turnUrls,
        username: process.env.TURN_USERNAME?.trim() ?? '',
        credential: process.env.TURN_CREDENTIAL?.trim() ?? '',
      },
    ]
  : [];

const render = (value, ice) =>
  `// Generated by scripts/ensure-env.mjs. Git-ignored: never commit a real key.\n` +
  `export const environment = {\n  googleMapsApiKey: ${JSON.stringify(value)},\n` +
  `  turnServers: ${JSON.stringify(ice)},\n};\n`;

if (key) {
  writeFileSync(target, render(key, turnServers));
  console.log('[ensure-env] Wrote environment.local.ts from environment variables.');
} else if (!existsSync(target)) {
  writeFileSync(target, render('', []));
  console.warn(
    '[ensure-env] No API key configured. Street View will be disabled until you set googleMapsApiKey in ' +
      'src/environments/environment.local.ts or provide GOOGLE_MAPS_API_KEY.',
  );
}
