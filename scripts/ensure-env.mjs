// Creates src/environments/environment.local.ts (git-ignored) before serve/build/test.
// - If GOOGLE_MAPS_API_KEY is set, the file is (re)written with that key.
// - Otherwise an existing file is kept, or a placeholder file without a key is created.
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'environments', 'environment.local.ts');
const key = process.env.GOOGLE_MAPS_API_KEY?.trim();

const render = (value) =>
  `// Generated by scripts/ensure-env.mjs. Git-ignored: never commit a real key.\n` +
  `export const environment = {\n  googleMapsApiKey: ${JSON.stringify(value)},\n};\n`;

if (key) {
  writeFileSync(target, render(key));
  console.log('[ensure-env] Wrote environment.local.ts from GOOGLE_MAPS_API_KEY.');
} else if (!existsSync(target)) {
  writeFileSync(target, render(''));
  console.warn(
    '[ensure-env] No API key configured. Street View will be disabled until you set googleMapsApiKey in ' +
      'src/environments/environment.local.ts or provide GOOGLE_MAPS_API_KEY.',
  );
}
